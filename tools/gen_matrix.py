#!/usr/bin/env python3
"""Generate docs/compatibility-matrix.md from ddhub/data/*.json so docs never drift from code.

    python3 tools/gen_matrix.py
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

data = {n: json.loads((REPO / "ddhub" / "data" / f"{n}.json").read_text()) for n in ("platforms", "backends", "programs")}
platforms = {k: v for k, v in data["platforms"].items() if not k.startswith("_")}
backends = {k: v for k, v in data["backends"].items() if not k.startswith("_")}
programs = {k: v for k, v in data["programs"].items() if not k.startswith("_")}
results_path = REPO / "docs" / "test-results" / "e2e-results.json"
tested = {"gb": "Libbet (homebrew) via RetroArch 1.18.0 + mGBA core 0.10.2: played, input verified (container, Xvfb)",
          "pc": "SuperTux 0.6.3 native: launched, menus + world map input verified; in-level play NOT verified (container, Xvfb)"}

PRIORITY = {"mature": "1 - set up first", "good": "2", "partial": "3 - per-title", "experimental": "4 - not integrated",
            "unsupported": "- use alternatives"}

out = ["# Compatibility matrix (DD Hub integration status)", "",
       "Generated by `tools/gen_matrix.py` from `ddhub/data/*.json`. Do not edit by hand.", "",
       "Three different things are kept apart here:", "",
       "1. **Upstream status** - what the emulator projects themselves report (sources and dates: "
       "[research/compatibility.md](research/compatibility.md), accessed 2026-11-18).",
       "2. **DD Hub integration** - which launch methods the hub knows how to find, configure and start.",
       "3. **Tested here** - what was actually played in a recorded test. Only two rows have that, and only in the "
       "build container (no GPU, no audio, no physical controller) - **nothing has been tested on your hardware yet**.", "",
       "Priority assumes a mid-range Windows/Linux PC; check per-title lists for 3D-era systems.", ""]

makers = {}
for pid, p in platforms.items():
    makers.setdefault(p["maker"], []).append((pid, p))

for maker, items in makers.items():
    out += [f"## {maker}", "", "| Platform | Year | Upstream (best local option) | Integrated launch methods | You must provide | Priority | Tested here |",
            "|---|---|---|---|---|---|---|"]
    for pid, p in sorted(items, key=lambda t: t[1]["year"]):
        bl = []
        needs = []
        for bid in p.get("backends", []):
            b = backends[bid]
            prog = programs.get(b["program"], {})
            bl.append(b["name"] + (f" ([{prog.get('license', '')}]({prog['homepage']}))" if prog.get("homepage") else ""))
            for r in b.get("requires", []):
                if r.get("platform") and r["platform"] != pid:
                    continue
                n = r["note"] + (" (optional)" if r.get("optional") else "")
                if n not in needs:
                    needs.append(n)
        alt = p.get("alternatives")
        cell = "<br>".join(bl) if bl else "**none integrated**"
        if alt:
            cell += f"<br>*Alternatives:* {alt}"
        note = p.get("note", "")
        up = p["upstream"] + (f" - {note}" if note else "")
        out.append(f"| {p['name']} (`{pid}`) | {p['year'] or ''} | {up} | {cell} | {'; '.join(needs) or 'game files you own'} | "
                   f"{PRIORITY.get(p['upstream'], '')} | {tested.get(pid, 'untested')} |")
    out.append("")

out += ["## Launch methods and their features", "",
        "Features are what the backend itself provides; the hub only displays them and never claims more.", "",
        "| Method | Kind | Program license | Exit tracking | Save states | Rewind | Netplay | Achievements |", "|---|---|---|---|---|---|---|---|"]
for bid, b in backends.items():
    f = b.get("features", {})
    prog = programs.get(b["program"], {})
    yn = lambda k: "yes" if f.get(k) is True else "-"
    out.append(f"| {b['name']} (`{bid}`) | {b['kind']} | {prog.get('license', 'n/a')}{' - ' + b['license_note'] if b.get('license_note') else ''} | "
               f"{b.get('tracking')} | {yn('save_states')} | {yn('rewind')} | {yn('netplay')} | "
               f"{f['achievements'] if isinstance(f.get('achievements'), str) else '-'} |")
out.append("")
(REPO / "docs" / "compatibility-matrix.md").write_text("\n".join(out))
print("wrote docs/compatibility-matrix.md")
